// Copies businesses, leads and chat messages from the old Node/MongoDB app into D1.
// Produces a .sql file; nothing is written to Cloudflare by this script.
//
//   MONGO_URI=mongodb://127.0.0.1:27017/whatsapp_realestate \
//   TOKEN_ENCRYPTION_KEY=<same value as the Worker secret> \
//   node scripts/migrate-from-mongo.mjs migration.sql
//
//   then:  npx wrangler d1 execute whatsapp-agent --remote --file migration.sql   (or --local)
//
// Vendors keep their existing API keys (only the hash is copied). Bot Studio texts become a real-estate flow.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { encryptToken } from '../src/lib/crypto.js';
import { flowFromTemplate, DEFAULT_MESSAGES } from '../src/lib/templates.js';
import { validateFlow, validateProfile, validateAi } from '../src/lib/flow.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(path.join(here, '../../package.json')); // the old app's node_modules (mongoose)
const mongoose = require('mongoose');

const out = process.argv[2];
const { MONGO_URI, TOKEN_ENCRYPTION_KEY } = process.env;
if (!out || !MONGO_URI || !TOKEN_ENCRYPTION_KEY) {
  console.error('Usage: MONGO_URI=... TOKEN_ENCRYPTION_KEY=... node scripts/migrate-from-mongo.mjs <output.sql>');
  process.exit(1);
}

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const iso = (d) => (d ? new Date(d).toISOString() : null);
const uuid = () => crypto.randomUUID();
// Old placeholders → new ones.
const conv = (t) => String(t || '').replace(/\{project\}/g, '{business}').replace(/\{slot\}/g, '{visit}');

/** Old Bot Studio content → real-estate flow with the vendor's own texts and options. */
function flowFromBotContent(bc) {
  const flow = flowFromTemplate('real_estate');
  if (!bc) return flow;
  const s = Object.fromEntries(flow.steps.map((x) => [x.id, x]));
  if (bc.welcomeText) s.home.text = conv(bc.welcomeText);
  if (bc.configOptions?.length) s.home.options = bc.configOptions.map((o) => ({ id: o.id, title: o.title || o.label, label: o.label, description: '', next: null }));
  for (const [from, to] of [['configListHeader', 'listHeader'], ['configListButton', 'listButton'], ['configSectionTitle', 'listSection']]) if (bc[from]) s.home[to] = conv(bc[from]);
  if (bc.budgetText) s.budget.text = conv(bc.budgetText);
  if (bc.budgetOptions?.length) s.budget.options = bc.budgetOptions.map((o) => ({ id: o.id, title: o.title || o.label, label: o.label, description: o.description || '', next: null }));
  for (const [from, to] of [['budgetHeader', 'listHeader'], ['budgetButtonLabel', 'listButton'], ['budgetSectionTitle', 'listSection']]) if (bc[from]) s.budget[to] = conv(bc[from]);
  if (bc.brochureCaption) s.brochure.text = conv(bc.brochureCaption);
  if (bc.slotText) s.visit.text = conv(bc.slotText);
  if (bc.slotPlan?.length) s.visit.plan = bc.slotPlan;
  if (bc.confirmationText) s.done.text = conv(bc.confirmationText);
  const m = { ...DEFAULT_MESSAGES };
  for (const [from, to] of [['completedText', 'completed'], ['optOutText', 'optOut'], ['nudgeText', 'nudge'], ['handoffText', 'handoff'], ['slotPassedText', 'slotPassed'], ['errorText', 'error']]) if (bc[from]) m[to] = conv(bc[from]);
  flow.messages = m;
  return flow;
}

const STATUS = { BROADCAST_SENT: 'CONTACTED', ENGAGED: 'ENGAGED', QUALIFIED: 'QUALIFIED', VISIT_CONFIRMED: 'CONVERTED', COLD: 'COLD' };

await mongoose.connect(MONGO_URI);
const db = mongoose.connection.db;
const tenants = await db.collection('tenants').find({}).toArray();
const lines = ['-- Generated by scripts/migrate-from-mongo.mjs on ' + new Date().toISOString()];
let nLeads = 0; let nMsgs = 0;

for (const t of tenants) {
  const id = uuid();
  const pd = t.projectDetails || {};
  const bc = t.botContent || null;
  const flowCheck = validateFlow(flowFromBotContent(bc));
  if (flowCheck.errors.length) console.warn(`! ${t.businessName}: flow warnings → ${flowCheck.errors.join('; ')} (saved anyway, fix in Flow Builder)`);
  const profile = validateProfile({
    displayName: pd.projectName || t.businessName, address: pd.siteAddress, latitude: pd.latitude, longitude: pd.longitude, faq: [],
    documentName: bc?.brochureFileName ? conv(bc.brochureFileName).replace(/\{business\}/g, pd.projectName || t.businessName) : '',
  }).value;
  profile.documentUrl = pd.brochurePdfUrl || null;
  const tpl = t.templates || {};
  lines.push(`INSERT INTO tenants (id, business_name, industry, phone_number_id, waba_id, access_token_enc, api_key_hash, admin_phone, tier, is_active, profile, flow, ai, templates, created_at, updated_at) VALUES (${[
    id, t.businessName, 'real_estate', t.phoneNumberId, t.wabaId || '', await encryptToken(TOKEN_ENCRYPTION_KEY, t.accessToken), t.apiKeyHash || null, t.adminNotificationPhone,
    t.tier ?? 0, t.isActive === false ? 0 : 1, JSON.stringify(profile), JSON.stringify(flowCheck.value), JSON.stringify(validateAi({ enabled: false }).value),
    JSON.stringify({ broadcastName: tpl.broadcastName || null, broadcastLanguage: tpl.broadcastLanguage || null, broadcastHasParams: tpl.broadcastHasParams ?? null, adminAlertName: tpl.adminAlertName || null, adminAlertLanguage: tpl.adminAlertLanguage || null }),
    iso(t.createdAt) || new Date().toISOString(), iso(t.updatedAt) || new Date().toISOString(),
  ].map(q).join(', ')});`);

  for (const l of await db.collection('leads').find({ tenantId: t._id }).toArray()) {
    nLeads++;
    const data = {};
    if (l.configuration && l.configuration !== 'Unspecified') data.configuration = l.configuration;
    if (l.budget && l.budget !== 'Unspecified') data.budget = l.budget;
    if (l.visitSlot) data.visit = l.visitSlot;
    lines.push(`INSERT INTO leads (id, tenant_id, phone, name, status, data, booked_at, last_broadcast_at, last_broadcast_message_id, broadcast_status, broadcast_status_at, broadcast_error, admin_alert_status, admin_alert_at, admin_alert_message_id, admin_alert_error, last_message_at, last_message_preview, last_message_direction, last_message_sent_by, last_inbound_at, unread_count, bot_paused, created_at, updated_at) VALUES (${[
      uuid(), id, l.phone, l.name && l.name !== 'Valued Customer' ? l.name : '', STATUS[l.status] || 'CONTACTED', JSON.stringify(data), iso(l.visitAt),
      iso(l.lastBroadcastAt), l.lastBroadcastMessageId || null, l.broadcastStatus || null, iso(l.broadcastStatusAt), l.broadcastError || null,
      l.adminAlertStatus || null, iso(l.adminAlertAt), l.adminAlertMessageId || null, l.adminAlertError || null,
      iso(l.lastMessageAt), l.lastMessagePreview || null, l.lastMessageDirection || null, l.lastMessageSentBy || null, iso(l.lastInboundAt),
      l.unreadCount || 0, l.botPaused ? 1 : 0, iso(l.createdAt) || new Date().toISOString(), iso(l.updatedAt) || new Date().toISOString(),
    ].map(q).join(', ')});`);
  }

  for (const m of await db.collection('messages').find({ tenantId: t._id }).sort({ createdAt: 1 }).toArray()) {
    nMsgs++;
    lines.push(`INSERT INTO messages (id, tenant_id, phone, direction, sent_by, type, text, meta, wa_message_id, status, error, created_at) VALUES (${[
      uuid(), id, m.phone, m.direction, m.sentBy, m.type, m.text || '', m.meta ? JSON.stringify(m.meta) : null, m.waMessageId || null, m.status || 'sent', m.error || null, iso(m.createdAt),
    ].map(q).join(', ')});`);
  }
  console.log(`✓ ${t.businessName}`);
}

fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(`Wrote ${out}: ${tenants.length} business(es), ${nLeads} leads, ${nMsgs} messages.`);
await mongoose.disconnect();
